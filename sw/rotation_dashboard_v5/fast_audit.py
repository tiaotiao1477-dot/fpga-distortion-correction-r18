I64_MAX = (1 << 63) - 1
I64_MIN = -(1 << 63)
WIDTH, HEIGHT = 1920, 1080


class Int64PreflightError(OverflowError):
    """Raised before vector arithmetic when a configuration is not proven safe."""


def round_shift_signed_array(values: np.ndarray, shift: int) -> np.ndarray:
    """Python-reference round-to-nearest, ties-away-from-zero on int64 arrays."""
    array = np.asarray(values, dtype=np.int64)
    if shift < 0:
        raise ValueError("array shift must be nonnegative")
    if shift == 0:
        return array.copy()
    if shift >= 63:
        raise ValueError("array shift must be below 63")
    low = int(array.min(initial=0))
    high = int(array.max(initial=0))
    max_magnitude = max(-low, high)
    if low <= I64_MIN or max_magnitude > I64_MAX - (1 << (shift - 1)):
        raise Int64PreflightError("rounding magnitude/half addition could overflow int64")
    magnitude = np.where(array < 0, -array, array)
    rounded = (magnitude + np.int64(1 << (shift - 1))) >> np.int64(shift)
    return np.where(array < 0, -rounded, rounded).astype(np.int64, copy=False)


def prove_int64_bounds(config, spec: FixedPointSpec | None = None,
                       words: tuple[int, ...] | None = None,
                       terms: Any | None = None,
                       proof_scope: str = 'measured_profile') -> dict[str, int]:
    """Prove all tile arithmetic fits signed int64 for generated R6 geometry.

    The accepted affine is the centered rotation/crop generated by this module:
    Q16 matrix terms are at most 1.0 and translation is bounded by the canvas
    center geometry. ``measured_profile`` retains the frozen narrow coefficient
    limits. ``predicted_brown`` uses explicit CNN Brown bounds with exact
    measured K and proves every operation in Python big integers before NumPy.
    """
    spec = FixedPointSpec() if spec is None else spec
    if type(spec) is not FixedPointSpec or spec != FixedPointSpec():
        raise ValueError('The vector proof supports only the frozen default FixedPointSpec')
    if words is None:
        words = config_words(config)
    if terms is None:
        terms = _prepare_fixed_camera_terms(config.profile, spec)
    if (config.output_width, config.output_height) != (WIDTH, HEIGHT):
        raise Int64PreflightError("V3 audit is bound to 1920x1080 full-frame geometry")
    a00, a01, a02, a10, a11, a12 = map(int, words[12:18])
    if max(abs(a00), abs(a01), abs(a10), abs(a11)) > (1 << 16):
        raise Int64PreflightError("affine matrix is outside the generated rotation/crop bound")
    translation_bound = ((WIDTH - 1 + HEIGHT - 1 + (WIDTH - 1) / 2 + (HEIGHT - 1) / 2) * (1 << 16)) + 2
    if max(abs(a02), abs(a12)) > math.ceil(translation_bound):
        raise Int64PreflightError("affine translation is outside the centered rotation/crop bound")
    if proof_scope not in ('measured_profile', 'predicted_brown'):
        raise ValueError(f'unsupported int64 proof scope: {proof_scope}')
    coefficient_limits = {
        "fx_q": 1 << 27, "fy_q": 1 << 27, "cx_q": 1 << 26, "cy_q": 1 << 26,
        "inv_fx_q": 1 << 14, "inv_fy_q": 1 << 14,
    }
    if proof_scope == 'measured_profile':
        coefficient_limits.update({"k1_q": 1 << 23, "k2_q": 1 << 22,
                                   "p1_q": 1 << 15, "p2_q": 1 << 14})
    else:
        # Predicted scope retains exact measured K and applies the CNN's public
        # Brown bounds before proving each quantized product below in Python
        # big integers. It does not widen or skip any int64 arithmetic check.
        for name, limit in (("k1", .55), ("k2", .35), ("p1", .006), ("p2", .006)):
            if not math.isfinite(float(getattr(config.profile, name))) or abs(float(getattr(config.profile, name))) > limit:
                raise Int64PreflightError(f"predicted Brown coefficient {name} exceeds its physical bound")
    for name, limit in coefficient_limits.items():
        if abs(int(getattr(terms, name))) >= limit:
            raise Int64PreflightError(f"measured profile term {name} exceeds proven bound")

    bounds: dict[str, int] = {}

    def keep(name: str, value: int) -> int:
        value = abs(int(value))
        if value > I64_MAX:
            raise Int64PreflightError(f"{name} exceeds signed int64 preflight")
        bounds[name] = value
        return value

    def add(name: str, left: int, right: int) -> int:
        return keep(name, left + right)

    def mul(name: str, left: int, right: int) -> int:
        return keep(name, left * right)

    def rounded(name: str, value: int, shift: int) -> int:
        keep(name + "_rounding_add", value + (1 << (shift - 1)))
        return keep(name, (value + (1 << (shift - 1))) >> shift)

    affine_x = add("affine_x_q16_wide", add("affine_x_terms", mul("affine_x_u_product", abs(a00), WIDTH - 1),
                    mul("affine_x_v_product", abs(a01), HEIGHT - 1)), abs(a02))
    affine_y = add("affine_y_q16_wide", add("affine_y_terms", mul("affine_y_u_product", abs(a10), WIDTH - 1),
                    mul("affine_y_v_product", abs(a11), HEIGHT - 1)), abs(a12))
    ideal_x = min(affine_x, (1 << 31) - 1)
    ideal_y = min(affine_y, (1 << 31) - 1)
    dx = add("delta_x_q16", ideal_x, abs(terms.cx_q))
    dy = add("delta_y_q16", ideal_y, abs(terms.cy_q))
    nxp = mul("product_normalize_x", dx, abs(terms.inv_fx_q))
    nyp = mul("product_normalize_y", dy, abs(terms.inv_fy_q))
    x = rounded("x_q16", nxp, 24)
    y = rounded("y_q16", nyp, 24)
    x2p, y2p, xyp = mul("product_x2", x, x), mul("product_y2", y, y), mul("product_xy", x, y)
    x2, y2, xy = rounded("x2_q16", x2p, 16), rounded("y2_q16", y2p, 16), rounded("xy_q16", xyp, 16)
    r2 = add("r2_q16", x2, y2)
    r4p = mul("product_r4", r2, r2)
    r4 = rounded("r4_q16", r4p, 16)
    k1p, k2p = mul("product_k1_r2", abs(terms.k1_q), r2), mul("product_k2_r4", abs(terms.k2_q), r4)
    k1r2, k2r4 = rounded("k1_r2_q16", k1p, 24), rounded("k2_r4_q16", k2p, 24)
    gain_partial = add("gain_partial_q16", 1 << 16, k1r2)
    gain = add("gain_q16", gain_partial, k2r4)
    rxp, ryp = mul("product_radial_x", x, gain), mul("product_radial_y", y, gain)
    rx, ry = rounded("radial_x_q16", rxp, 16), rounded("radial_y_q16", ryp, 16)
    p2base = add("p2_x_base_q16", r2, 2 * x2)
    p1base = add("p1_y_base_q16", r2, 2 * y2)
    p1xyp, p2xyp = mul("product_p1_xy", abs(terms.p1_q), xy), mul("product_p2_xy", abs(terms.p2_q), xy)
    p1xy, p2xy = rounded("p1xy_q16", p1xyp, 24), rounded("p2xy_q16", p2xyp, 24)
    p2bp, p1bp = mul("product_p2_x_base", abs(terms.p2_q), p2base), mul("product_p1_y_base", abs(terms.p1_q), p1base)
    p2term, p1term = rounded("p2_x_term_q16", p2bp, 24), rounded("p1_y_term_q16", p1bp, 24)
    tx = add("tangential_x_q16", 2 * p1xy, p2term)
    ty = add("tangential_y_q16", p1term, 2 * p2xy)
    xd, yd = add("xd_q16", rx, tx), add("yd_q16", ry, ty)
    pxp, pyp = mul("product_projection_x", abs(terms.fx_q), xd), mul("product_projection_y", abs(terms.fy_q), yd)
    projected_x, projected_y = rounded("projected_x_q16", pxp, 16), rounded("projected_y_q16", pyp, 16)
    sx, sy = add("src_x_q16", projected_x, abs(terms.cx_q)), add("src_y_q16", projected_y, abs(terms.cy_q))
    rounded("src_x_q10_unclipped", sx, 6); rounded("src_y_q10_unclipped", sy, 6)
    return bounds


def fixed_tile(config, u, v, spec: FixedPointSpec | None = None,
               words: tuple[int, ...] | None = None, terms: Any | None = None,
               proof_scope: str = 'measured_profile') -> dict[str, Any]:
    """Vectorize the original scalar fixed/float stages for one raster tile.

    This internal vectorizer is intentionally restricted to the frozen default
    FixedPointSpec; caller-selected formats require a corresponding new proof.
    The explicit proof scope keeps prediction limits opt-in.
    """
    spec = FixedPointSpec() if spec is None else spec
    if type(spec) is not FixedPointSpec or spec != FixedPointSpec():
        raise ValueError('The vector tile supports only the frozen default FixedPointSpec')
    words = config_words(config) if words is None else words
    terms = _prepare_fixed_camera_terms(config.profile, spec) if terms is None else terms
    prove_int64_bounds(config, spec, words, terms, proof_scope=proof_scope)
    u_raw, v_raw = np.asarray(u), np.asarray(v)
    if u_raw.dtype.kind not in 'iu' or v_raw.dtype.kind not in 'iu':
        raise TypeError('Raster coordinates must be integer arrays')
    u_outside = bool(u_raw.size and (np.any(u_raw < 0) or np.any(u_raw >= config.profile.width)))
    v_outside = bool(v_raw.size and (np.any(v_raw < 0) or np.any(v_raw >= config.profile.height)))
    if u_outside or v_outside:
        raise ValueError('Raster coordinates must remain inside the configured output frame')
    u, v = np.broadcast_arrays(u_raw.astype(np.int64, copy=False),
                               v_raw.astype(np.int64, copy=False))
    a00, a01, a02, a10, a11, a12 = (np.int64(x) for x in words[12:18])
    px = a00 * u + a01 * v + a02
    py = a10 * u + a11 * v + a12
    affine_ox = (px < -(1 << 31)) | (px > (1 << 31) - 1)
    affine_oy = (py < -(1 << 31)) | (py > (1 << 31) - 1)
    ix = np.clip(px, -(1 << 31), (1 << 31) - 1)
    iy = np.clip(py, -(1 << 31), (1 << 31) - 1)
    affine_overflow = affine_ox | affine_oy
    ix = np.where(affine_overflow, 0, ix).astype(np.int64, copy=False)
    iy = np.where(affine_overflow, 0, iy).astype(np.int64, copy=False)

    dx, dy = ix - np.int64(terms.cx_q), iy - np.int64(terms.cy_q)
    np_x, np_y = dx * np.int64(terms.inv_fx_q), dy * np.int64(terms.inv_fy_q)
    x, y = round_shift_signed_array(np_x, 24), round_shift_signed_array(np_y, 24)
    x2p, y2p, xyp = x * x, y * y, x * y
    x2, y2, xy = (round_shift_signed_array(z, 16) for z in (x2p, y2p, xyp))
    r2 = x2 + y2
    r4p = r2 * r2
    r4 = round_shift_signed_array(r4p, 16)
    k1p, k2p = np.int64(terms.k1_q) * r2, np.int64(terms.k2_q) * r4
    k1r2, k2r4 = round_shift_signed_array(k1p, 24), round_shift_signed_array(k2p, 24)
    gain_partial = np.int64(1 << 16) + k1r2
    gain = gain_partial + k2r4
    rxp, ryp = x * gain, y * gain
    rx, ry = round_shift_signed_array(rxp, 16), round_shift_signed_array(ryp, 16)
    p2base, p1base = r2 + 2 * x2, r2 + 2 * y2
    p1xyp, p2xyp = np.int64(terms.p1_q) * xy, np.int64(terms.p2_q) * xy
    p1xy, p2xy = round_shift_signed_array(p1xyp, 24), round_shift_signed_array(p2xyp, 24)
    p2bp, p1bp = np.int64(terms.p2_q) * p2base, np.int64(terms.p1_q) * p1base
    p2term, p1term = round_shift_signed_array(p2bp, 24), round_shift_signed_array(p1bp, 24)
    tx, ty = 2 * p1xy + p2term, p1term + 2 * p2xy
    xd, yd = rx + tx, ry + ty
    pxp, pyp = np.int64(terms.fx_q) * xd, np.int64(terms.fy_q) * yd
    projected_x, projected_y = round_shift_signed_array(pxp, 16), round_shift_signed_array(pyp, 16)
    src_x_internal, src_y_internal = projected_x + np.int64(terms.cx_q), projected_y + np.int64(terms.cy_q)
    src_x_candidate, src_y_candidate = round_shift_signed_array(src_x_internal, 6), round_shift_signed_array(src_y_internal, 6)
    cmin, cmax = -(1 << (spec.coordinate_width - 1)), (1 << (spec.coordinate_width - 1)) - 1
    saturated_x, saturated_y = (src_x_candidate < cmin) | (src_x_candidate > cmax), (src_y_candidate < cmin) | (src_y_candidate > cmax)
    src_x, src_y = np.clip(src_x_candidate, cmin, cmax), np.clip(src_y_candidate, cmin, cmax)

    xmax, ymax = (config.profile.width - 1) << 16, (config.profile.height - 1) << 16
    outside = (affine_overflow | saturated_x | saturated_y | (src_x_internal < 0) | (src_y_internal < 0) |
               (src_x_internal > xmax) | (src_y_internal > ymax))
    border = np.where(outside, 2, np.where((src_x_internal >= xmax) | (src_y_internal >= ymax), 1, 0)).astype(np.int8)
    q10x, q10y = src_x // (1 << spec.coordinate_frac_bits), src_y // (1 << spec.coordinate_frac_bits)
    invalid_taps = ((src_x_internal < 0) | (src_y_internal < 0) |
                    (src_x_internal >= xmax) | (src_y_internal >= ymax) |
                    (q10x < 0) | (q10x + 1 >= config.profile.width) |
                    (q10y < 0) | (q10y + 1 >= config.profile.height))

    trace = {
        "delta_x_q16": dx, "delta_y_q16": dy, "x_q16": x, "y_q16": y,
        "x2_q16": x2, "y2_q16": y2, "xy_q16": xy, "r2_q16": r2, "r4_q16": r4,
        "k1_r2_q16": k1r2, "k2_r4_q16": k2r4, "gain_partial_q16": gain_partial,
        "gain_q16": gain, "radial_x_q16": rx, "radial_y_q16": ry,
        "p1xy_q16": p1xy, "p2xy_q16": p2xy, "p2_x_base_q16": p2base,
        "p1_y_base_q16": p1base, "tangential_x_q16": tx, "tangential_y_q16": ty,
        "xd_q16": xd, "yd_q16": yd, "projected_x_q16": projected_x,
        "projected_y_q16": projected_y, "src_x_q16": src_x_internal,
        "src_y_q16": src_y_internal, "src_x_q10_unclipped": src_x_candidate,
        "src_y_q10_unclipped": src_y_candidate, "src_x_q10": src_x,
        "src_y_q10": src_y, "product_normalize_x": np_x, "product_normalize_y": np_y,
        "product_x2": x2p, "product_y2": y2p, "product_xy": xyp,
        "product_r4": r4p, "product_k1_r2": k1p, "product_k2_r4": k2p,
        "product_radial_x": rxp, "product_radial_y": ryp, "product_p1_xy": p1xyp,
        "product_p2_xy": p2xyp, "product_p2_x_base": p2bp, "product_p1_y_base": p1bp,
        "product_projection_x": pxp, "product_projection_y": pyp,
        "affine_x_q16_wide": px, "affine_y_q16_wide": py,
        "ideal_x_q16": ix, "ideal_y_q16": iy,
    }

    # Float diagnostics mirror combined_coordinate_stages operation order.
    uf, vf = u.astype(np.float64), v.astype(np.float64)
    affine = config.affine
    ideal_fx = affine.a00 * uf + affine.a01 * vf + affine.a02
    ideal_fy = affine.a10 * uf + affine.a11 * vf + affine.a12
    profile = config.profile
    fx, fy = (ideal_fx - profile.cx) / profile.fx, (ideal_fy - profile.cy) / profile.fy
    fx2, fy2, fxy = fx * fx, fy * fy, fx * fy
    fr2, fr4 = fx2 + fy2, (fx2 + fy2) * (fx2 + fy2)
    fk1r2, fk2r4 = profile.k1 * fr2, profile.k2 * fr4
    fgain = 1.0 + fk1r2 + fk2r4
    frx, fry = fx * fgain, fy * fgain
    ftx = 2.0 * profile.p1 * fxy + profile.p2 * (fr2 + 2.0 * fx2)
    fty = profile.p1 * (fr2 + 2.0 * fy2) + 2.0 * profile.p2 * fxy
    fxd, fyd = frx + ftx, fry + fty
    fsrcx, fsrcy = profile.fx * fxd + profile.cx, profile.fy * fyd + profile.cy
    float_trace = {"x": fx, "y": fy, "x2": fx2, "y2": fy2, "xy": fxy, "r2": fr2,
                   "r4": fr4, "k1_r2": fk1r2, "k2_r4": fk2r4, "gain": fgain,
                   "radial_x": frx, "radial_y": fry, "tangential_x": ftx,
                   "tangential_y": fty, "xd": fxd, "yd": fyd,
                   "src_x": fsrcx, "src_y": fsrcy}
    error = np.hypot(src_x.astype(np.float64) / (1 << spec.coordinate_frac_bits) - fsrcx,
                     src_y.astype(np.float64) / (1 << spec.coordinate_frac_bits) - fsrcy)
    return {"trace": trace, "float_trace": float_trace, "affine_overflow": affine_overflow,
            "saturated_x": saturated_x, "saturated_y": saturated_y, "border": border,
            "invalid_taps": invalid_taps, "errors": error}


def scalar_fixed_pixel(config, u: int, v: int, spec: FixedPointSpec | None = None):
    """Expose the frozen scalar integer oracle for targeted software comparison."""
    spec = spec or FixedPointSpec()
    words = config_words(config)
    terms = _prepare_fixed_camera_terms(config.profile, spec)
    trace: dict[str, int] = {}
    result = _combined_coordinate_fixed(u, v, config, spec, words[12:18], terms, trace=trace)
    return trace, result
